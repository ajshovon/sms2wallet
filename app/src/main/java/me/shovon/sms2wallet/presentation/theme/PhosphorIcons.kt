    /**
     * Builds one duotone icon.
     *
     * The 256x256 viewport is Phosphor's own grid; the 24dp default size matches
     * [IconSize.lg] so these drop straight into Material components.
     */
    private fun duotone(
        name: String,
        toneAlpha: Float,
        tone: String?,
        solid: List<String>,
    ): ImageVector = ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = VIEWPORT,
        viewportHeight = VIEWPORT,
    ).apply {
        if (tone != null) {
            addPath(
                pathData = PathParser().parsePathString(tone).toNodes(),
                fill = SolidColor(Color.Black),
                fillAlpha = toneAlpha,
            )
        }
        solid.forEach { d ->
            addPath(pathData = PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color.Black))
        }
    }.build()

    /** Phosphor draws on a 256x256 grid. */
    private const val VIEWPORT = 256f
